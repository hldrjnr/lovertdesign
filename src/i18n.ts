function getVal(obj: Messages, key: string): string {
  const direct = obj[key]
  if (typeof direct === 'string') return direct
  const parts = key.split('.')
  let cur: any = obj
  for (const p of parts) {
    if (cur == null || typeof cur !== 'object') return key
    cur = cur[p]
  }
  return typeof cur === 'string' ? cur : key
}

export function tx(key: string, params?: Record<string, string | number>): string {
  const lang = useStore.getState().language
  let msg = getVal(messages[lang], key)
  if (!msg) msg = getVal(messages['pt'], key)
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      msg = msg.replace(`{${k}}`, String(v))
    }
  }
  return msg
}

export function setLanguage(lang: Language) {
  useStore.getState().setLanguage(lang)
}

